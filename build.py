#!/usr/bin/env python3
"""Bundle src/*.lua into dist/FischHub.lua.

The luau CLI shipped in this environment has no io library, so the bundler
lives in Python. Module order matches the dependency chain: every module may
only __require one that appears before it in MODULES.
"""

import pathlib
import sys

MODULES = [
    "env", "util", "config", "scanner", "stealth", "motion",
    "minigame", "fishing", "economy", "quests",
    "esp", "anti", "learn", "ui", "main",
]

HEADER = """--[[
  Fisch Hub 2.0
  Bundled build. Generated by build.py from src/*.lua - do not edit this
  file directly, edit the module and rebuild.

  Toggle panel: RightControl.
  Console API: getgenv().FischHub
]]

local __modules = {}
local function __require(name)
	local module = __modules[name]
	assert(module, "module not loaded: " .. tostring(name))
	return module
end
"""


def main() -> int:
    root = pathlib.Path(__file__).resolve().parent
    parts = [HEADER]

    for name in MODULES:
        path = root / "src" / f"{name}.lua"
        if not path.is_file():
            print(f"missing module: {path}", file=sys.stderr)
            return 1
        source = path.read_text(encoding="utf-8")
        parts.append(f'__modules["{name}"] = (function()\n{source}\nend)()\n')

    bundle = "\n".join(parts)
    out = root / "dist" / "FischHub.lua"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(bundle, encoding="utf-8")

    print(f"built {out.relative_to(root)} - {len(MODULES)} modules, "
          f"{bundle.count(chr(10))} lines, {len(bundle)} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
